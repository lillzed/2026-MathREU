def policy_evaluation(pi, MDP, gamma=1.0, theta=1e-10):
    prev_V = np.zeros(len(MDP))
    while True:
        V = np.zeros(len(MDP))
        for s in range(len(MDP)):
            for prob, next_state, reward, done in MDP[s][pi(s)]:
                next_state = int(next_state)
                V[s] += (prob * 
                        (reward +
                         gamma * prev_V[next_state] * (not done)))
        if np.max(np.abs(prev_V - V)) < theta:
            break
        prev_V = V.copy()
    return V

def policy_improvement(v_function, MDP, gamma=1.0):
    Q = np.zeros((len(MDP), len(MDP[0])))
    for s in range(len(MDP)):
        for a in range(len(MDP[s])):
            for prob, next_state, reward, done in MDP[s][a]:
                next_state = int(next_state)
                Q[s][a] += prob *(reward + 
                                  gamma * v_function[next_state] * (not done))
    new_pi = lambda s: {s: a for s, a in enumerate(
                                        np.argmax(Q, axis=1))}[s]
    return new_pi

def optimal_policy(v_function, MDP, gamma=1.0):
    new_pi = policy_improvement(v_function, MDP, gamma)   # use v_function directly, don't re-evaluate it
    new_V = policy_evaluation(new_pi, MDP, gamma)
    if np.array_equal(v_function, new_V):                  # also: see note below on == comparison
        return new_pi
    else:
        return optimal_policy(new_V, MDP, gamma)

def value_iteration(MDP, gamma=1.0, theta=1e-10):
    V = np.zeros(len(MDP), dtype=np.float64)
    while True:
        Q = np.zeros((len(MDP), len(MDP[0])), dtype=np.float64)
        for s in range(len(MDP)):
            for a in range(len(MDP[s])):
                for prob, next_state, reward, done in MDP[s][a]:
                    next_state = int(next_state)
                    Q[s][a] += prob * (reward+gamma*V[next_state]*(not done))
        if np.max(np.abs(V - np.max(Q, axis=1))) < theta:
            break
        V = np.max(Q, axis=1)
    pi = lambda s: {s: a for s, a in enumerate(
                                        np.argmax(Q, axis=1))}[s]
    
    return V, pi

